    actual = [(row['property'], (model.resolver.live[56,
        int(row['after_identity'].rsplit(':', 1)[1])].address if row.get('after_identity') else row.get('after')))
        for row in receipt['journal'] if row['call'] == 'assign']
    assert actual == assignments
    assert ledger(model) == expected_ledger
    assert receipt['full_quick_zone_lifecycle'] is False
    assert receipt['save_executed'] is False
    for group in model.resolver.live.values():
        if group.identity.startswith('retained:'):
            assert group.levels[0].value == 'oops'


