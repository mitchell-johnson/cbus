def pp_name(role):
    return role + ('GroupNumber' if role.startswith('InternalRelay') else 'Output')


def base_pp(plant):
    result = dict.fromkeys(PP_NAMES, 0)
    for role in ROLES:
        result[pp_name(role)] = 255
    result.update(ApplicationNumber=56, Application=49, ZoneGroup=7,
        InternalPlantType=plant, InternalPlantModes=31, InternalPlantZones=30,
        InstalledZones=30, ControlledZones=30, CoolingPlantInstalledZones=30,
        HeatingPlantInstalledZones=30, VentingPlantInstalledZones=30,
        MeasuredZones=1, UIAllocatedZones=2, UnrelatedParameter=173,
        InstallationCode=0, EvapProgramEnabled=1, NonEvapProgramEnabled=1)
    return result


def retained(address, name, application=56):
    level = RemoteLevel(7, 'oops', f'retained-level:{application}:{address}:7',
        'Retained Level Ω', '<Level><Address>7</Address><Value>oops</Value></Level>')
    return RemoteGroup(application, address, f'retained:{application}:{address}', name,
        'Group', json.dumps({'keep': 'exact & Ω', 'address': address}), (level,))


def owner(plant=3, groups=((255, 'Unused'),), refs=None, installation=None, **kwargs):
    values = base_pp(plant)
    rows = tuple(retained(n, name) for n, name in groups)
    zone = retained(7, 'Zone communication', 172)
    other = retained(1, 'Unrelated Group', 202)
    apps = (RemoteApplication(56, 'application56', 'Lighting', rows, '<Opaque>keep</Opaque>'),
            RemoteApplication(172, 'application172', 'Air Conditioning', (zone,), ''),
            RemoteApplication(202, 'application202', 'Unrelated', (other,), '<Opaque>Ω</Opaque>'))
    graph = ProjectGraphSnapshot('QZOWNED', 11, 20, '//QZOWNED/11/20', (), apps, (),
        'sealed source shape', 'synthetic source hash')
    resolver = _GraphResolver(graph)
    references = {role: resolver.live.get((56, (refs or {}).get(role, 255))) for role in ROLES}
    for role, group in references.items():
        values[pp_name(role)] = 255 if group is None else group.address
    model = PlantTypeModel(values, references, resolver,
        zone_group=lambda: zone, current_installation=lambda: installation,
        plant_type=kwargs.pop('plant_type', lambda: plant), **kwargs)
    project = {'project': {'address': 'QZOWNED', 'identity': 'owned-project',
        'opaque': {'keep': 'exact'}, 'networks': [
            {'address': 11, 'identity': 'network11', 'interface': {'kind': 'synthetic-no-live-endpoint'},
             'applications': [{'address': 56, 'identity': 'application56', 'groups': list(rows)},
                              {'address': 202, 'identity': 'application202', 'groups': [other]},
                              {'address': 172, 'identity': 'application172', 'groups': [zone]}],
             'units': [{'address': 20, 'identity': 'selected-unit', 'parameters': deepcopy(values)},
                       {'address': 21, 'identity': 'unrelated-unit', 'parameters': {'OpaqueSetting': 'unchanged & Ω'}}]},
            {'address': 12, 'identity': 'network12', 'opaque': {'tail': 'unchanged'}}]}}
    return model, project


def current_project(model, original):
    project = deepcopy(original)
    network = project['project']['networks'][0]
    network['units'][0]['parameters'] = deepcopy(model.values)
    assert set(model.resolver.apps) == {a['address'] for a in network['applications']}
    for application in network['applications']:
        application['groups'] = [g for (app, _), g in model.resolver.live.items() if app == application['address']]
    return project


def expected_project(original, values, groups):
    result = deepcopy(original)
    network = result['project']['networks'][0]
    network['units'][0]['parameters'] = values
    retained_by_address = {g.address: g for g in network['applications'][0]['groups']}
    network['applications'][0]['groups'] = [
        replace(retained_by_address[n], name=name) if n in retained_by_address
        else RemoteGroup(56, n, f'planned-group:56:{n}', name, 'Group', '')
        for n, name in groups]
    return result


