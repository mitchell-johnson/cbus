    return [(('create' if row['call'] == 'CreateGroup' else 'ChangeTagName'),
        row.get('address', int(row['identity'].rsplit(':', 1)[1])),
        row.get('previous_name'), row['name']) for row in model.journal
        if row['call'] in ('CreateGroup', 'ChangeTagName')]


