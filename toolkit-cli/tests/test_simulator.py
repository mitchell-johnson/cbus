class SimulatorTests(unittest.TestCase):
    def wire(self, address, command, expected_size=None):
        with socket.create_connection(address, timeout=1) as conn:
            conn.settimeout(1)
            conn.sendall(command)
            if expected_size is None:
                return conn.recv(4096)
            reply = bytearray()
            while len(reply) < expected_size:
                data = conn.recv(expected_size - len(reply))
                if not data:
                    break
                reply.extend(data)
            return bytes(reply)

    def test_captured_identity_and_programming_ack_are_literal(self):
        sim = PCISimulator()
        with sim.running() as address:
            with PCIClient(*address) as client:
                self.assertEqual(client.identify(None, 1), b"PC_CNIED")
                self.assertEqual(client.identify(5, 1), b"KEYGL5  ")
                self.assertEqual(client.recall(4, 0x30, 1), b"\x03")
                self.assertEqual(client.write(5, 0, b"\x41\xa0\x00", addressing="programming", ack_tag=0x41),
                                 AcknowledgeCAL(0, 0x41))
                self.assertEqual(client.write(5, 1, b"\x42\x12\x34", addressing="programming", ack_tag=0x42),
                                 AcknowledgeCAL(1, 0x42))
        replies = [bytes.fromhex(record["hex"]) for record in sim.wire_log if record["direction"] == "tx"]
        self.assertIn(b"g.890150435F434E49454421\r\n", replies)
        self.assertIn(b"j.8605100100320041F1\r\n", replies)
        self.assertIn(b"k.8605100100320142EF\r\n", replies)

    def test_written_raw_blocks_survive_reconnect_and_process_state_reload(self):
        with tempfile.TemporaryDirectory() as folder:
            state = Path(folder) / "state.json"
            sim = PCISimulator(state_path=state)
            with sim.running() as address:
                with PCIClient(*address) as client:
                    client.write(5, 0, b"\x41\xac\x00", addressing="programming")
                    client.write(5, 1, b"\x42\x01\x02\x03")
                with PCIClient(*address) as client:
                    self.assertEqual(client.recall(5, 0, 3), b"\x41\xac\x00")
                    self.assertEqual(client.recall(5, 1, 4), b"\x42\x01\x02\x03")
            # Construct a different server instance from its disk image.
            reloaded = PCISimulator(state_path=state)
            with reloaded.running() as address:
                with PCIClient(*address) as client:
                    self.assertEqual(client.recall(5, 0, 3), b"\x41\xac\x00")
                    self.assertEqual(client.recall(5, 1, 2), b"\x42\x01")
                    self.assertEqual(client.identify(5, 1), b"KEYGL5  ")
            self.assertEqual(reloaded.snapshot(), sim.snapshot())

    def test_captured_physical_address_selection_and_literal_segmented_registers(self):
        sim = PCISimulator(profile="captured", fragment_sizes=(1, 3, 2))
        with sim.running() as address:
            with PCIClient(*address) as client:
                self.assertEqual(client.write(5, 0, bytes.fromhex("411000"),
                                              addressing="programming", ack_tag=0x41),
                                 AcknowledgeCAL(0, 0x41))
                self.assertEqual(client.recall(5, 1, 2, addressing="programming"),
                                 bytes.fromhex("38FF"))
                self.assertEqual(client.recall(5, 0xFA, 44, addressing="programming"),
                                 bytes.fromhex("FFFFFFFFFFFFFFFFFFFFFFFF381B381938213818"
                                               "FFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF"))
                self.assertEqual(client.recall(5, 0xFB, 9, addressing="programming"), b"01.05.00\x00")
        wire = b"".join(bytes.fromhex(record["hex"]) for record in sim.wire_log
                        if record["direction"] == "tx")
        # Independent, literal proxy.log frames, not responses generated by the client codec.
        for frame in (b"8605100100320041F1\r\n", b"8605100100830138FFA9\r\n",
                      b"860510010091FAFFFFFFFFFFFFFFFFFFFFFFFF381B381941\r\n",
                      b"860510010091FA38213818FFFFFFFFFFFFFFFFFFFFFFFF3C\r\n",
                      b"86051001008DFAFFFFFFFFFFFFFFFFFFFFFFFFE9\r\n",
                      b"86051001008AFB30312E30352E3030005D\r\n"):
            self.assertIn(frame, wire)

    def test_physical_writes_recall_and_disk_reload_keep_selected_memory(self):
        with tempfile.TemporaryDirectory() as folder:
            state = Path(folder) / "state.json"
            sim = PCISimulator(profile="captured", state_path=state,
                               physical_memory={5: {0x10000 + i: i for i in range(40)}})
            with sim.running() as address:
                with PCIClient(*address) as client:
                    client.write(5, 0, bytes.fromhex("41000001"), addressing="programming", ack_tag=0x41)
                    self.assertEqual(client.recall(5, 1, 33, addressing="programming"), bytes(range(33)))
                    client.write(5, 0, bytes.fromhex("4100000100"), addressing="programming", ack_tag=0x41)
                    client.write(5, 1, bytes.fromhex("42AABB"), addressing="programming", ack_tag=0x42)
                    # RECALL after WRITE uses the advanced pointer.
                    self.assertEqual(client.recall(5, 1, 2, addressing="programming"), b"\x02\x03")
            reloaded = PCISimulator(profile="captured", state_path=state)
            with reloaded.running() as address:
                with PCIClient(*address) as client:
                    # The volatile selector is not persisted; select explicitly after restart.
                    with self.assertRaises(PCIRejected):
                        client.recall(5, 1, 1, addressing="programming")
                with PCIClient(*address) as client:
                    client.write(5, 0, bytes.fromhex("41000001"), addressing="programming", ack_tag=0x41)
                    self.assertEqual(client.recall(5, 1, 4, addressing="programming"), bytes.fromhex("AABB0203"))
            self.assertEqual(reloaded.snapshot(), sim.snapshot())

    def test_physical_unknown_bytes_and_forms_reject_without_mutating_memory(self):
        sim = PCISimulator(profile="captured")
        before = sim.snapshot()
        with sim.running() as address:
            actions = [lambda client: client.recall(5, 1, 1, addressing="programming"),
                       lambda client: client.write(5, 0, b"\x41\x10", addressing="programming"),
                       lambda client: client.write(5, 0, b"\x40\x10\x00", addressing="programming"),
                       lambda client: client.recall(5, 0xFA, 45, addressing="programming"),
                       lambda client: client.recall(4, 1, 1, addressing="programming")]
            for action in actions:
                with PCIClient(*address) as client:
                    with self.assertRaises(PCIRejected):
                        action(client)
            for action in (lambda client: client.recall(5, 1, 3, addressing="programming"),
                           lambda client: client.write(5, 1, b"\x42\xAA\xBB\xCC", addressing="programming")):
                with PCIClient(*address) as client:
                    client.write(5, 0, b"\x41\x10\x00", addressing="programming")
                    with self.assertRaises(PCIRejected):
                        action(client)
        self.assertEqual(sim.snapshot(), before)

