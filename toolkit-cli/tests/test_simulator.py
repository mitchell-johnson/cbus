    def test_mmi_presence_encoding_covers_all_boundaries_without_phantom_units(self):
        expected = {0: 1, 87: 2, 88: 1, 175: 2, 176: 1, 255: 2}
        units = [UnitState(unit, mmi_state=state) for unit, state in expected.items()]
        sim = PCISimulator(units, local_unit=0)
        with sim.running() as address:
            response = self.wire(address, b"\\05FF00FAFF00g\r", 160)
        self.assertTrue(response.startswith(b"g."))
        frames = response[2:].split(b"\r\n")[:-1]
        self.assertEqual(len(frames), 3)
        recovered = {}
        for text, start in zip(frames, (0, 88, 176)):
            frame = bytes.fromhex(text.decode())
            self.assertEqual(sum(frame) % 256, 0)
            self.assertEqual(frame[1:3], bytes((255, start)))
            self.assertEqual(frame[0] & 31, len(frame) - 2)
            for i, byte in enumerate(frame[3:-1]):
                for pair in range(4):
                    state = (byte >> (2 * pair)) & 3
                    if state:
                        recovered[start + 4 * i + pair] = state
        self.assertEqual(recovered, expected)

    def test_header_compression_reuses_previous_unit_and_isolates_connections(self):
        sim = PCISimulator()
        with sim.running() as address:
            with socket.create_connection(address, timeout=1) as conn:
                conn.settimeout(1)
                conn.sendall(b"\\4604002101g\r")
                self.assertIn(b"8604100089014B455945312020201D", conn.recv(200))
                conn.sendall(b"2102h\r")
                # The response is from unit4, whose firmware is2.5, not CNI5.5.
                self.assertEqual(conn.recv(200), b"h.860410008902322E352E3030202078\r\n")
            with PCIClient(*address) as client:
                self.assertEqual(client.identify(None, 2), b"5.5.00  ")

    def test_client_local_calls_after_bus_calls_cannot_hit_cached_bus_destination(self):
        units = [UnitState(16, {1: b"PC_CNIED"}, {0x20: b"\x10", 7: b"\x10"}, {7: 0x44}),
                 UnitState(5, {1: b"TEST"}, {7: b"\x20"}, {7: 0x55})]
        sim = PCISimulator(units)
        with sim.running() as address:
            with PCIClient(*address) as client:
                client.write(5, 7, b"\x99", ack_tag=0x55)
                client.write(None, 7, b"\xaa", ack_tag=0x44)
                self.assertEqual(client.recall(5, 7, 1), b"\x99")
                self.assertEqual(client.recall(None, 7, 1), b"\xaa")
        requests = [bytes.fromhex(row["hex"]) for row in sim.wire_log if row["direction"] == "rx"]
        self.assertEqual(requests[1], b"@1A2001\r")
        self.assertEqual(requests[2], b"\\461000A207AAh\r")
        self.assertEqual(sim.units[5].parameters[7], b"\x99")
        self.assertEqual(sim.units[16].parameters[7], b"\xaa")

