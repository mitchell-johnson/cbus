class SourcePinTests(unittest.TestCase):
    @unittest.skipUnless(VENDOR.is_dir(), 'Private decompiled eDLT sources are absent')
    def test_modeled_excerpts_match_the_retained_original_sources(self):
        for path, digest in ORIGINAL_SOURCES.items():
            self.assertEqual(hashlib.sha256((VENDOR / path).read_bytes()).hexdigest(),
                             digest, path)
        for path, first, last, digest in ORIGINAL_EXCERPTS:
            lines = (VENDOR / path).read_bytes().split(b'\n')[first - 1:last]
            self.assertEqual(hashlib.sha256(b'\n'.join(lines)).hexdigest(),
                             digest, (path, first, last))

    def test_excerpt_logic_literal_cases(self):
        both = EdltDisplayPreferences(display_hex=True, display_address_value=True)
        # Address.PadLeft(3, '0') pads the stored text, never truncating it.
        self.assertEqual(formatted_display('1234', 'N', both), '1234 (4D2h) - N')
        # AddressAsInt uses int.TryParse and falls back to zero.
        self.assertEqual(formatted_display('x', 'N', both), '00x (00h) - N')
        self.assertEqual(address_as_int(' +7 '), 7)
        self.assertEqual(address_as_int('7.0'), 0)
        self.assertEqual(address_as_int('2147483648'), 0)
        # Negative Int32 ToString("X") is two's complement.
        self.assertEqual(formatted_display('-1', 'N', both), '0-1 (FFFFFFFFh) - N')
        # Trim() applies to the prefix only; the TagName is appended verbatim.
        hex_only = EdltDisplayPreferences(display_hex=True)
        self.assertEqual(formatted_display(5, ' spaced ', hex_only), '(05h) -  spaced ')
        self.assertEqual(formatted_display(5, '', EdltDisplayPreferences()), '')


class RegistryTests(unittest.TestCase):
    def test_absent_key_and_values_use_static_false_defaults(self):
        absent = EdltDisplayPreferences.from_registry(key_present=False)
        self.assertEqual(absent, EdltDisplayPreferences())
        self.assertEqual(EdltDisplayPreferences.from_registry({}), EdltDisplayPreferences())
        with self.assertRaisesRegex(EdltError, 'absent Preferences key'):
            EdltDisplayPreferences.from_registry({'DisplayHexAddress': 1}, key_present=False)

    def test_int_cast_greater_than_zero(self):
        for raw, expected in ((0, False), (1, True), (2, True), (0x7fffffff, True),
                              (0x80000000, False), (0xffffffff, False), (-1, False)):
            with self.subTest(raw=raw):
                values = {name: raw for name in REGISTRY_NAMES}
                self.assertEqual(
                    EdltDisplayPreferences.from_registry(values),
                    EdltDisplayPreferences(*(expected,) * 5))
        for bad in (True, '1', 1.0, 2**32, -(2**31) - 1, None):
            with self.subTest(bad=bad), self.assertRaises(EdltError):
                EdltDisplayPreferences.from_registry({'SortModeGroups': bad})
        with self.assertRaisesRegex(EdltError, 'five eDLT names'):
            EdltDisplayPreferences.from_registry({'DisplayHex': 1})

    def test_each_registry_name_selects_exactly_one_flag(self):
        for index, name in enumerate(REGISTRY_NAMES):
            flags = [False] * 5; flags[index] = True
            self.assertEqual(EdltDisplayPreferences.from_registry({name: 1}),
                             EdltDisplayPreferences(*flags))

    def test_document_roundtrip_and_toolkit_store_adapter(self):
        for flags in itertools.product((False, True), repeat=5):
            value = preferences(flags)
            self.assertEqual(EdltDisplayPreferences.from_dict(
                json.loads(json.dumps(value.as_dict()))), value)
        store = {'tag_hex': True, 'tag_override': 0, 'sort_applications': 1,
                 'sort_groups': False, 'sort_levels': 255}
        self.assertEqual(EdltDisplayPreferences.from_toolkit_display_values(store),
                         EdltDisplayPreferences(True, False, True, False, True))
        with self.assertRaises(EdltError):
            EdltDisplayPreferences.from_dict({'format': 'x', 'registry_key_present': True,
                                              'values': {}})


class DisplayListTests(unittest.TestCase):
    def test_all_32_flag_combinations(self):
        for flags in itertools.product((False, True), repeat=5):
            display_hex, display_value, sort_apps, sort_groups, sort_levels = flags
            prefs = preferences(flags)
            texts = DISPLAYS[(display_hex, display_value)]
            with self.subTest(flags=flags):
                for kind, rows, by_address in (('application', APPLICATIONS, sort_apps),
                                               ('group', GROUPS, sort_groups),
                                               ('level', LEVELS, sort_levels)):
                    result = display_list(kind, rows, prefs)
                    self.assertEqual(tuple(row.address for row in result),
                                     ORDERS[kind][by_address], kind)
                    for row in result:
                        expected = '<Unused>' if row.address == 255 else texts[row.address]
                        self.assertEqual(row.formatted_display, expected)
                        self.assertEqual(row.name, next(
                            item.name for item in rows if item.address == row.address))

    def test_case_insensitive_ties_are_stable_and_reported(self):
        rows = tuple(CachedDisplay(address, name, name) for address, name in (
            (9, 'b'), (4, 'A'), (7, 'a'), (1, '_x'), (2, 'Z'), (3, 'A')))
        by_name = order(rows, by_address=False)
        self.assertEqual([row.address for row in by_name], [4, 7, 3, 9, 2, 1])
        self.assertEqual(name_ties(rows), ((1, 2, 5),))
        self.assertEqual([row.address for row in order(tuple(reversed(rows)),
                                                         by_address=False)],
                         [3, 7, 4, 9, 2, 1])
        self.assertEqual(order(by_name, by_address=False), by_name)
        self.assertEqual([row.address for row in order(rows, by_address=True)],
                         [1, 2, 3, 4, 7, 9])
        # Non-ASCII names use one-character upper mappings; ß has none.
        rows = tuple(CachedDisplay(address, name, name) for address, name in (
            (1, 'é'), (2, 'É'), (3, 'ß'), (4, 'z')))
        self.assertEqual([row.address for row in order(rows, by_address=False)],
                         [4, 1, 2, 3])

    def test_application_cache_presentation_is_idempotent_and_keeps_identity(self):
        lifecycle = LifecycleCache((202, 56, 100, 7), (
            LifecycleGroup(56, 255, True, (False,) * 4, True, ()),))
        cache = ApplicationCache(lifecycle, True, APPLICATIONS, (
            CachedGroupList(56, True, GROUPS),
            CachedGroupList(202, False, ())))
        prefs = EdltDisplayPreferences(True, True, False, True, False)
        presented = present_application_cache(cache, prefs)
        self.assertIs(presented.lifecycle, cache.lifecycle)
        self.assertEqual([row.address for row in presented.applications], [100, 56, 7, 202])
        self.assertEqual([row.formatted_display for row in presented.find_group_list(56).groups],
                         ['<Unused>', '000 (00h) - _Spare', '003 (03h) - Zone',
                          '010 (0Ah) - Kitchen'])
        self.assertFalse(presented.find_group_list(202).complete)
        self.assertEqual(present_application_cache(presented, prefs), presented)
        self.assertEqual(
            [row.formatted_display for row in presented.application_choices(
                primary=56, secondary=100)['secondary']],
            ['<Unused>', '100 (64h) - air'])
        report = evidence(prefs, presented)
        self.assertEqual(report['case_insensitive_name_ties'],
                         [{'kind': 'application', 'application': None, 'addresses': [56, 7]}])
        self.assertEqual(evidence(None)['display_projection'], 'exact TagName database view')


