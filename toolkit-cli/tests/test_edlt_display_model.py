class PlanThreadingTests(unittest.TestCase):
    """Explicit preferences reach the automatic ordered caches unchanged."""

    def setUp(self):
        import tests.test_edlt_parent_auto_cache as auto
        auto.ParentAutomaticApplicationCacheTests.setUp(self)
        from tests.test_edlt_parent_cache_panels import operations
        self.operations = operations()

    def plan(self, preferences=None):
        from cbus_toolkit.edlt_parent_metadata import plan_native_parent_metadata
        return plan_native_parent_metadata(
            self.client.xml(), '//TEST/254/p/20', self.source, self.editor,
            self.operations, display_preferences=preferences)

    def test_parent_ordered_cache_uses_supplied_preferences_only(self):
        legacy = self.plan()
        names = [row.name for row in legacy.cache.applications]
        addresses = [row.address for row in legacy.cache.applications]
        self.assertEqual([row.formatted_display for row in legacy.cache.applications], names)

        absent = self.plan(EdltDisplayPreferences.from_registry(key_present=False))
        self.assertEqual([row.name for row in absent.cache.applications],
                         sorted(names, key=lambda name: name.upper()))
        self.assertEqual([row.formatted_display for row in absent.cache.applications],
                         [row.name for row in absent.cache.applications])
        evidence_row = absent.as_dict()['automatic_ordered_application_cache']
        self.assertTrue(evidence_row['toolkit_display_preferences_supplied'])
        self.assertFalse(evidence_row['toolkit_registry_display_and_sort_preferences_observed'])
        self.assertNotEqual(absent.semantic_source(), legacy.semantic_source())

        numbered = self.plan(EdltDisplayPreferences(
            display_address_value=True, sort_applications_by_address=True,
            sort_groups_by_address=True))
        self.assertEqual([row.address for row in numbered.cache.applications], sorted(addresses))
        self.assertEqual([row.formatted_display for row in numbered.cache.applications],
                         [f'{row.address:03d} - {row.name}' for row in numbered.cache.applications])
        for row in numbered.cache.group_lists:
            groups = [group.address for group in row.groups]
            self.assertEqual(groups, sorted(groups, key=lambda value: (value != 255, value)))
        self.assertEqual(numbered.parent_plan.changes, legacy.parent_plan.changes)
        with self.assertRaisesRegex(ValueError, 'EdltDisplayPreferences'):
            self.plan({'DisplayHexAddress': 1})

    def test_parent_cli_threads_the_preference_document(self):
        from unittest.mock import patch
        values = {name: list(value) for name, value in self.source.items()}
        with tempfile.TemporaryDirectory() as root:
            files = {name: Path(root) / name for name in (
                'values.json', 'project.xml', 'operations.json', 'preferences.json')}
            files['values.json'].write_text(json.dumps(values))
            files['project.xml'].write_text(self.client.xml())
            files['operations.json'].write_text(json.dumps(list(self.operations)))
            files['preferences.json'].write_text(json.dumps(EdltDisplayPreferences(
                display_hex=True).as_dict()))
            stdout, stderr = io.StringIO(), io.StringIO()
            with patch.object(cli, '_edlt_parent_transaction', return_value=self.editor), \
                    redirect_stdout(stdout), redirect_stderr(stderr):
                status = cli.main(list(map(str, [
                    'edlt', 'parent-transaction-plan', files['values.json'],
                    '--project-xml', files['project.xml'], '--unit', '//TEST/254/p/20',
                    '--operations', files['operations.json'],
                    '--display-preferences', files['preferences.json']])))
            self.assertEqual(status, 0, stderr.getvalue())
            result = json.loads(stdout.getvalue())
        applications = result['metadata_cache']['applications']
        self.assertTrue(all(row['formatted_display'].startswith('(')
                            and row['formatted_display'].endswith(') - ' + row['name'])
                            for row in applications))
        self.assertEqual(result['automatic_ordered_application_cache'][
            'toolkit_display_preferences']['values']['DisplayHexAddress'], 1)


