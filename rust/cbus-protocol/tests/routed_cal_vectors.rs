//! P3.01 vectors for one-, two- and six-hop routed CAL WRITE/RECALL.
//!
//! The committed file `testdata/vectors/routed_cal.jsonl` pins the exact
//! wire bytes of the Python `pci_routing.RoutedCALCommand` oracle (direct
//! addressing, confirmation `g`) for one-, two- and six-bridge routes, plus the
//! independent Reply Network ACK derivation of Python
//! `commissioning_route.plan_commissioning_route` (nearest bridge is the
//! outer source, the local PCI is the destination, entries are the remaining
//! bridges plus the replying unit). Every `expect_frame_ascii` value was
//! generated by the oracle and cross-checked before commit.
//!
//! This test drives the pure Rust `cbus-protocol` codec only: no sockets, no
//! PCI, no movement or persistence claim. Error rows prove over-long routes,
//! payloads and counts refuse before any I/O could occur.

use cbus_protocol::pci_observation::{
    routed_recall_request, routed_write_expected_ack, routed_write_request,
};
use serde_json::Value;
use std::collections::HashSet;

const VECTORS: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../testdata/vectors/routed_cal.jsonl"
);

fn rows() -> Vec<Value> {
    let text = std::fs::read_to_string(VECTORS)
        .unwrap_or_else(|e| panic!("missing routed-CAL vectors {VECTORS}: {e}"));
    let rows: Vec<Value> = text
        .lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| serde_json::from_str(l).expect("vector line is valid JSON"))
        .collect();
    assert!(!rows.is_empty(), "vector file must not be empty");
    rows
}

fn get_str(item: &Value, id: &str, key: &str) -> String {
    item.get(key)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("{id}: missing string field {key}"))
        .to_string()
}

fn get_u8(item: &Value, id: &str, key: &str) -> u8 {
    let n = item
        .get(key)
        .and_then(Value::as_u64)
        .unwrap_or_else(|| panic!("{id}: missing integer field {key}"));
    u8::try_from(n).unwrap_or_else(|_| panic!("{id}: field {key} out of u8 range"))
}

fn get_bool(item: &Value, id: &str, key: &str) -> bool {
    item.get(key)
        .and_then(Value::as_bool)
        .unwrap_or_else(|| panic!("{id}: missing boolean field {key}"))
}

fn get_bridges(item: &Value, id: &str) -> Vec<u8> {
    item.get("bridges")
        .and_then(Value::as_array)
        .unwrap_or_else(|| panic!("{id}: missing array field bridges"))
        .iter()
        .map(|bridge| {
            u8::try_from(
                bridge
                    .as_u64()
                    .unwrap_or_else(|| panic!("{id}: bridge is not an integer")),
            )
            .unwrap_or_else(|_| panic!("{id}: bridge out of u8 range"))
        })
        .collect()
}

fn get_u8_list(item: &Value, id: &str, key: &str) -> Vec<u8> {
    item.get(key)
        .and_then(Value::as_array)
        .unwrap_or_else(|| panic!("{id}: missing array field {key}"))
        .iter()
        .map(|entry| {
            u8::try_from(
                entry
                    .as_u64()
                    .unwrap_or_else(|| panic!("{id}: field {key} holds a non-integer")),
            )
            .unwrap_or_else(|_| panic!("{id}: field {key} out of u8 range"))
        })
        .collect()
}

#[test]
fn routed_cal_vectors() {
    let rows = rows();
    let mut ids = HashSet::new();
    for item in &rows {
        let id = get_str(item, "<row>", "id");
        assert!(ids.insert(id.clone()), "duplicate vector id {id}");
        let kind = get_str(item, &id, "kind");
        match kind.as_str() {
            "write_encode" => {
                let data = hex::decode(get_str(item, &id, "data_hex"))
                    .unwrap_or_else(|_| panic!("{id}: data_hex is not hex"));
                let frame = routed_write_request(
                    &get_bridges(item, &id),
                    get_u8(item, &id, "unit"),
                    get_u8(item, &id, "parameter"),
                    &data,
                    get_bool(item, &id, "command_checksum"),
                )
                .unwrap_or_else(|error| panic!("{id}: routed WRITE refused valid input: {error}"));
                assert_eq!(
                    frame,
                    get_str(item, &id, "expect_frame_ascii").as_bytes(),
                    "{id}: routed WRITE wire differs from the oracle"
                );
            }
            "recall_encode" => {
                let count = get_u8(item, &id, "count");
                let frame = routed_recall_request(
                    &get_bridges(item, &id),
                    get_u8(item, &id, "unit"),
                    get_u8(item, &id, "parameter"),
                    count,
                    get_bool(item, &id, "command_checksum"),
                )
                .unwrap_or_else(|error| panic!("{id}: routed RECALL refused valid input: {error}"));
                assert_eq!(
                    frame,
                    get_str(item, &id, "expect_frame_ascii").as_bytes(),
                    "{id}: routed RECALL wire differs from the oracle"
                );
            }
            "ack_path" => {
                let (outer, destination, entries) = routed_write_expected_ack(
                    &get_bridges(item, &id),
                    get_u8(item, &id, "local"),
                    get_u8(item, &id, "unit"),
                )
                .unwrap_or_else(|error| panic!("{id}: ACK path refused valid input: {error}"));
                assert_eq!(
                    outer,
                    get_u8(item, &id, "expect_outer"),
                    "{id}: outer differs"
                );
                assert_eq!(
                    destination,
                    get_u8(item, &id, "expect_destination"),
                    "{id}: destination differs"
                );
                assert_eq!(
                    entries,
                    get_u8_list(item, &id, "expect_entries"),
                    "{id}: route entries differ"
                );
            }
            "write_encode_error" => {
                let data = hex::decode(get_str(item, &id, "data_hex"))
                    .unwrap_or_else(|_| panic!("{id}: data_hex is not hex"));
                assert!(
                    routed_write_request(
                        &get_bridges(item, &id),
                        get_u8(item, &id, "unit"),
                        get_u8(item, &id, "parameter"),
                        &data,
                        get_bool(item, &id, "command_checksum"),
                    )
                    .is_err(),
                    "{id}: routed WRITE accepted an invalid route or payload"
                );
            }
            "recall_encode_error" => {
                assert!(
                    routed_recall_request(
                        &get_bridges(item, &id),
                        get_u8(item, &id, "unit"),
                        get_u8(item, &id, "parameter"),
                        get_u8(item, &id, "count"),
                        get_bool(item, &id, "command_checksum"),
                    )
                    .is_err(),
                    "{id}: routed RECALL accepted an invalid route or count"
                );
            }
            "ack_path_error" => {
                assert!(
                    routed_write_expected_ack(
                        &get_bridges(item, &id),
                        get_u8(item, &id, "local"),
                        get_u8(item, &id, "unit"),
                    )
                    .is_err(),
                    "{id}: ACK derivation accepted an invalid route"
                );
            }
            other => panic!("{id}: unknown vector kind {other}"),
        }
    }
}
